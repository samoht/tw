let oklch color_name shade =
  let color_map =
    match String.lowercase_ascii color_name with
    | "gray" -> gray
    | "slate" -> slate
    | "mauve" -> mauve
    | "olive" -> olive
    | "mist" -> mist
    | "taupe" -> taupe
    | "zinc" -> zinc
    | "neutral" -> neutral
    | "stone" -> stone
    | "red" -> red
    | "orange" -> orange
    | "amber" -> amber
    | "yellow" -> yellow
    | "lime" -> lime
    | "green" -> green
    | "emerald" -> emerald
    | "teal" -> teal
    | "cyan" -> cyan
    | "sky" -> sky
    | "blue" -> blue
    | "indigo" -> indigo
    | "violet" -> violet
    | "purple" -> purple
    | "fuchsia" -> fuchsia
    | "pink" -> pink
    | "rose" -> rose
    | _ -> []
  in
  List.assoc_opt shade color_map

let oklch_css color_name shade =
  match oklch color_name shade with
  | Some oklch -> Some (oklch_to_css oklch)
  | None -> None

